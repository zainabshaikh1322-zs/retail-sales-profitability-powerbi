Retail Sales & Profitability Dashboard
An interactive Power BI project exploring retail sales and profitability
across products, regions, customer segments, and time.
Tools Used
- Microsoft Power BI Desktop
- Power Query
- DAX
- Excel
Key KPIs
- Total Sales: approximately 2.33M
- Total Profit: approximately 292.30K
- Profit Margin: 12.56%
- Total Orders: approximately 5K
- Total Units Sold: approximately 39K
- Loss-Making Orders: approximately 1K
Figures are rounded as displayed in the current dashboard. Confirm the
currency/unit and reset slicers to All before publishing.
Dashboard Features
- Sales trend by year
- Sales and profit by category and sub-category
- Regional sales and profit comparison
- Customer-segment performance
- State-level sales
- Interactive slicers for year, region, segment, state/province, and
  ship mode
Initial Findings
- Technology has the highest sales among the displayed product
  categories.
- West and East contribute the largest shares of regional sales.
- Consumer customers account for about half of total sales.
- Tables and Bookcases appear to have negative total profit in the
  current sub-category chart.
These are initial descriptive observations. They do not establish why a
result occurred. See [Business Insights and
Recommendations](Business_Insights_and_Recommendations.md) for the
detailed analysis and suggested follow-up checks.
How to Open
1. Download the .pbix file from this repository.
2. Open it using Power BI Desktop.
3. Use the slicers to explore the report.
Limitations
The dashboard is descriptive, not causal. The latest year may be
incomplete, and possible causes of negative profit need further
investigation. Add the original dataset source and attribution once
confirmed, and only redistribute data when its license permits.
